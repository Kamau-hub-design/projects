create table public.products (
  id integer generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  category text not null check (category in ('Clothing', 'Bags', 'Home')),
  price_cents integer not null check (price_cents between 1 and 10000000),
  color text not null default '' check (char_length(color) <= 120),
  tag text not null default '' check (char_length(tag) <= 60),
  image text not null check (image ~ '^photo-[a-zA-Z0-9-]+$'),
  description text not null check (char_length(description) between 1 and 1000),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create trigger products_updated_at
before update on public.products
for each row execute procedure public.update_updated_at();

alter table public.products enable row level security;

create policy "Anyone can read active products"
on public.products for select
to anon, authenticated
using (is_active or (select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

create policy "Admins can insert products"
on public.products for insert
to authenticated
with check ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

create policy "Admins can update products"
on public.products for update
to authenticated
using ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
with check ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

revoke all on public.products from anon, authenticated;
grant select on public.products to anon, authenticated;
grant insert, update on public.products to authenticated;
grant usage, select on sequence public.products_id_seq to authenticated;

